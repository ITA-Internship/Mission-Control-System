# flake8: noqa: E501
from dataclasses import dataclass
from datetime import date
from decimal import Decimal

from drones.models import Drone, WriteOffRecord


@dataclass(frozen=True)
class DroneSpecSeed:
    frame_type: str
    motor_model: str
    battery_type: str
    battery_capacity_mah: int
    camera_model: str
    vtx_model: str
    flight_controller: str
    firmware_version: str
    max_speed_kmh: Decimal
    typical_range_km: Decimal
    max_range_km: Decimal
    typical_flight_time_min: Decimal
    max_flight_time_min: Decimal
    frequency_mhz: int
    payload_capacity_g: int | None


@dataclass(frozen=True)
class DroneSeed:
    serial_number: str
    inventory_number: str
    name: str
    drone_model_name: str
    status: str
    unit_code: str
    acquired_at: date
    notes: str
    spec: DroneSpecSeed


@dataclass(frozen=True)
class StatusHistorySeed:
    drone_serial: str
    from_status: str
    to_status: str
    changed_by_username: str | None
    reason: str
    related_mission_title: str | None


@dataclass(frozen=True)
class WriteOffSeed:
    drone_serial: str
    reason: str
    reason_description: str
    authorized_by_username: str | None
    related_mission_title: str | None
    document_number: str
    written_off_at: date


@dataclass(frozen=True)
class DroneModelSeed:
    name: str
    manufacturer: str
    description: str | None
    supported_classifications: list[str]
    is_active: bool = True


